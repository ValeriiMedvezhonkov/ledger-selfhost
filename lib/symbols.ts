export function categorySymbol(
  icon: string | null | undefined,
  slug: string | null | undefined,
): SymbolName {
  if (icon != null && icon in CATEGORY_SYMBOL) {
    return CATEGORY_SYMBOL[icon] ?? "category";
  }
  if (slug != null && slug in CATEGORY_SYMBOL_BY_SLUG) {
    return CATEGORY_SYMBOL_BY_SLUG[slug] ?? "category";
  }
  return "category";
}
